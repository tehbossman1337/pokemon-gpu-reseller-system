"""Regenerates static_embedded.py from static/index.html (run after any UI edit; the build also runs it)."""
import os
h = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(h, "static", "index.html"), encoding="utf-8").read()
# repr() gives an exact Python literal (json.dumps would split emoji into surrogate pairs that can't be sent)
open(os.path.join(h, "static_embedded.py"), "w", encoding="utf-8").write("# generated by gen_embedded.py - do not edit\nHTML = " + repr(html) + "\n")
print("static_embedded.py written", len(html), "chars of UI")
